"""FFT fast solver for A x = b (equal skill, three players), by the method of images.

Live state (x1, x2, x3) sits at grid point (x1, x2). A = I - Q, where Q averages over the six neighbour
offsets (1, 0), (-1, 0), (0, 1), (0, -1), (1, -1), (-1, 1). The stencil is translation invariant, and the
three sides x1 = 0, x2 = 0, x3 = 0 are mirror lines of it. The reflection across x_a = 0 sends x_a -> -x_a
and adds x_a to the other two coordinates. In (x1, x2):

    R1(x1, x2) = (-x1, x2 + x1),   R2(x1, x2) = (x1 + x2, -x2),   R3(x1, x2) = (N - x2, N - x1).

With coordinates mod P = 3N these generate a group of 18 maps g(x) = L x + t: 6 linear parts L times the
translations (0, 0), (N, N), (2N, 2N). Half have det L = +1 and half det L = -1.

Odd extension: put sign(g) b(x) at g(x) for every live x and every g, on a P x P periodic grid. The periodic
problem (I - Q) U = that grid has the symbol

    sigma(alpha, beta) = 1 - (cos alpha + cos beta + cos(alpha - beta)) / 3,   alpha = 2 pi k / P, beta = 2 pi l / P,

which is zero only at k = l = 0 (where the odd data has zero mean). So one FFT, a division and an inverse
FFT solve it. The solution is odd under every reflection, so it is 0 on the mirror lines: exactly the
boundary condition of A x = b. Chunk 1's eigenvalues are sigma at (k, l) -> (2k + l, k + 2l) on this grid.
"""
import functools

import numpy as np
import scipy.fft

from .states import StateSpace


@functools.lru_cache(maxsize=None)
def _group(N):
    """The 18 maps (L, t, sign) generated by R1, R2, R3, coordinates mod P = 3N (breadth-first closure)."""
    P = 3 * N
    gens = [
        (np.array([[-1, 0], [1, 1]]), np.array([0, 0])),   # R1
        (np.array([[1, 1], [0, -1]]), np.array([0, 0])),   # R2
        (np.array([[0, -1], [-1, 0]]), np.array([N, N])),  # R3
    ]
    identity = (np.eye(2, dtype=int), np.array([0, 0]))
    key = lambda L, t: (tuple(L.ravel()), tuple(t % P))
    seen = {key(*identity): identity}
    queue = [identity]
    while queue:
        L, t = queue.pop(0)
        for La, ta in gens:  # R_a after g: x -> La (L x + t) + ta
            new = (La @ L, (La @ t + ta) % P)
            k = key(*new)
            if k not in seen:
                seen[k] = new
                queue.append(new)
    group = [(L, t, int(round(np.linalg.det(L)))) for L, t in seen.values()]
    signs = [s for _, _, s in group]
    assert len(group) == 18, f"group has {len(group)} elements, expected 18"
    assert signs.count(1) == 9 and signs.count(-1) == 9, "expected 9 elements of each sign"
    return group


@functools.lru_cache(maxsize=2)
def _symbol(N):
    """sigma on the rfft2 half grid, shape (P, P // 2 + 1), with sigma[0, 0] set to 1 (that entry is zeroed)."""
    P = 3 * N
    alpha = 2 * np.pi * np.arange(P)[:, None] / P
    beta = 2 * np.pi * np.arange(P // 2 + 1)[None, :] / P
    sigma = 1 - (np.cos(alpha) + np.cos(beta) + np.cos(alpha - beta)) / 3
    sigma[0, 0] = 1.0
    return sigma


def fft_solve(N, b):
    """Solve build_A(StateSpace(N)) x = b. b and x are in StateSpace order; b is not modified."""
    S = StateSpace(N)
    P = 3 * N
    b = np.asarray(b, dtype=np.float64)
    X = np.stack([S.x1, S.x2])  # shape (2, n)

    # odd extension onto the P x P torus (each g is one-to-one, so no index repeats within a g)
    U = np.zeros((P, P))
    for L, t, sign in _group(N):
        gx = (L @ X + t[:, None]) % P
        U[gx[0], gx[1]] += sign * b

    # periodic solve: divide by the symbol, drop the zero frequency
    Uh = scipy.fft.rfft2(U, workers=1)
    Uh /= _symbol(N)
    Uh[0, 0] = 0.0
    x = scipy.fft.irfft2(Uh, s=(P, P), workers=1)
    return x[S.x1, S.x2].copy()
